"""AI asset inbox: AI video sent from the ops portal (AI Tools > Send to Growth Desk), with where it came from.

The portal copies each finished video from the PREDCT GPU's bucket to the render bucket's AI inbox
(config/ai_inbox.json `inbox_prefix`), next to a sidecar JSON: model, model revision, licence, prompt, seed,
checksum, brand, duration and size. `import_inbox` turns each pair into an asset:

* rights: PLN made it with a model whose licence allows commercial use (only those licences are imported), so the
  asset is owned by PLN, worldwide, with the model and licence on record. No human rights entry is needed.
* people: none (an AI scene). A sidecar that says it shows a real person's likeness is flagged ai_generated_person
  and keeps the athlete unverified until someone confirms them on the asset page.
* flags: ai_generated always, so every post made from it carries the AI label requirement and the TikTok AIGC /
  YouTube altered-or-synthetic flags (adapters/providers.py). A sidecar "disclosure": "none" (a reviewer cleared it
  as clearly stylised in the portal) drops the label flag; it is still recorded as AI in the provenance.

Idempotent: an asset id comes from the job id, so importing twice changes nothing.
"""
from __future__ import annotations

import json
import os
import re

from .accounts import canonical_brand_id, load_brands, resolve_brand
from .config import CONFIG_DIR
from .db import DB, now_iso

VIDEO = (".mp4", ".mov", ".m4v", ".webm")


class AiInboxError(ValueError):
    pass


def policy() -> dict:
    return json.loads((CONFIG_DIR / "ai_inbox.json").read_text())


def license_ok(lic: str, allowed: dict) -> bool:
    key = re.sub(r"[^a-z0-9.]+", "-", (lic or "").lower()).strip("-")
    return any(key == k or key.startswith(k + "-") for k in allowed)


def asset_id_for(meta: dict, stem: str) -> str:
    job = re.sub(r"[^a-z0-9-]+", "-", str(meta.get("job_id") or stem.rsplit("/", 1)[-1]).lower()).strip("-")
    return f"ai-{job}"[:80]


def _s3_list(bucket: str, prefix: str) -> list[str]:
    from .predct import _list
    return [o["key"] for o in _list(bucket, prefix)]


def _s3_read(bucket: str, key: str) -> bytes:
    import boto3
    return boto3.client("s3").get_object(Bucket=bucket, Key=key)["Body"].read()


def brand_for(v: str) -> dict:
    """A brand id (putt_tour) or any name/alias the registry knows; unknown falls back to PLN."""
    for b in load_brands():
        if b["brand_id"] == v:
            return b
    try:
        return resolve_brand(v)
    except KeyError:
        return resolve_brand("pln")


def asset_row(meta: dict, path: str, aid: str, pol: dict) -> dict:
    brand = brand_for(str(meta.get("brand") or "pln"))
    likeness = bool(meta.get("likeness"))
    flags = {"ai_generated": meta.get("disclosure", "label") != "none"}
    if likeness:
        flags["ai_generated_person"] = True
    dur = meta.get("duration_s")
    dur = float(dur) if isinstance(dur, (int, float)) else None
    model = str(meta.get("model", ""))[:80]
    lic = str(meta.get("license", ""))[:120]
    prompt = str(meta.get("prompt", ""))[:2000]
    title = (meta.get("title") or prompt.split(".")[0] or aid)[:120]
    return {
        "asset_id": aid, "brand_id": canonical_brand_id(brand), "source_brand_name": brand["name"],
        "title": title, "description": prompt,
        "media_path": path, "media_present": True, "sha256": str(meta.get("sha256", ""))[:64],
        "content_id": str(meta.get("job_id", ""))[:80], "parent_asset_id": "",
        "provenance": (f"ops AI Tools (PREDCT GPU): {model}@{str(meta.get('model_version', ''))[:12]}, licence {lic}; "
                       f"seed {meta.get('seed', '')}; requested by {meta.get('requested_by', '')}; sent by {meta.get('sent_by', '')}"),
        "owner": pol.get("owner", "Pro League Network"), "license": f"PLN original made with {model} ({lic})",
        "territory": pol.get("territory", ["WORLDWIDE"]), "rights_expires_at": None, "rights_verified": True,
        "people_verified": not likeness, "music_cleared": True,  # the sound is generated by the same licensed model
        "sponsors": [], "sponsor_approved": False, "people": [], "facts": [],
        "moments": [{"start": 0.0, "end": dur or 5.0, "label": "AI clip", "kind": "payoff"}] if dur else [],
        "flags": flags, "series": "", "event_name": "", "event_date": None, "duration_s": dur,
        "width": meta.get("width"), "height": meta.get("height"), "has_audio": bool(meta.get("has_audio", True)),
        "probe": {"ai_tools": {k: meta.get(k) for k in ("model", "model_version", "license", "prompt", "seed", "job_id",
                                                         "gcs_folder", "requested_by", "sent_by", "sent_at")}},
        "transcript": [], "is_sample": False, "ingested_at": now_iso(),
    }


def import_inbox(db: DB, bucket: str | None = None, lister=_s3_list, reader=_s3_read, actor: str = "ai-inbox") -> dict:
    """Every AI video in the inbox with a sidecar and a cleared model licence becomes an asset (rights clear)."""
    bucket = bucket or os.environ.get("PLN_RENDER_BUCKET")
    if not bucket:
        raise AiInboxError("needs PLN_RENDER_BUCKET")
    pol = policy()
    keys = lister(bucket, pol["inbox_prefix"])
    media = {k.rsplit(".", 1)[0]: k for k in keys if k.lower().endswith(VIDEO)}
    added, skipped = [], []
    for side in (k for k in keys if k.endswith(".json")):
        stem = side[:-5]
        if stem not in media:
            skipped.append({"key": side, "why": "no video next to the sidecar"})
            continue
        try:
            meta = json.loads(reader(bucket, side))
        except (ValueError, KeyError) as e:
            skipped.append({"key": side, "why": f"unreadable sidecar: {e}"})
            continue
        if not license_ok(meta.get("license", ""), pol["licenses"]):
            skipped.append({"key": side, "why": f"model licence '{meta.get('license')}' is not cleared for commercial use"})
            continue
        aid = asset_id_for(meta, stem)
        if db.get("assets", "asset_id", aid):
            continue
        db.insert("assets", asset_row(meta, f"s3://{bucket}/{media[stem]}", aid, pol), upsert_key="asset_id")
        db.audit(actor, "asset_ingested", "assets", aid, {"source": "ai-inbox", "sidecar": side})
        added.append(aid)
    if added or skipped:
        db.audit(actor, "ai_inbox_imported", "assets", "", {"added": len(added), "skipped": skipped[:20]})
    return {"added": added, "skipped": skipped}
